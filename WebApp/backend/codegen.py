"""Generates standalone Python (.py) scripts and Jupyter Notebooks (.ipynb) from GlobeProject JSON."""

import json
from typing import Dict
from .models import GlobeProject


def generate_python_and_notebook(project: GlobeProject) -> Dict[str, str]:
    """Generates a standalone Python script and Jupyter Notebook replicating the GlobeProject.

    Args:
        project (GlobeProject): Project configuration.

    Returns:
        dict: Dictionary containing 'python_script' and 'notebook_json'.
    """
    meta = project.metadata
    geom = project.geometry
    mag = project.magnets
    exp = project.export

    lines = [
        f'"""{meta.name}',
        "",
        f"{meta.description}",
        "Auto-generated by Globe3D Studio WebApp.",
        '"""',
        "",
        "import os",
        "import numpy as np",
        "import globe3d",
        "from globe3d import (",
        "    GlobeModel,",
        "    GeographicGrid,",
        "    GridDisplacer,",
        "    ConstantDisplacer,",
        "    PointDisplacer,",
        "    LineDisplacer,",
        "    PolygonDisplacer,",
        "    GridColourer,",
        "    ImageColourer,",
        "    ConstantColourer,",
        "    PointColourer,",
        "    LineColourer,",
        "    PolygonColourer,",
        "    SymbolColourer,",
        "    PoleLabelColourer,",
        "    TextColourer,",
        "    MagnetSettings,",
        "    calculate_displacement_scale,",
        "    datasets,",
        ")",
        "",
    ]

    if project.mode == "paleo" or project.paleo_config.enabled:
        pc = project.paleo_config
        tracked_repr = repr([
            {"name": loc.name, "lat": loc.lat, "lon": loc.lon, "color": loc.color, "size": pc.location_marker_size_deg}
            for loc in pc.tracked_locations
        ])
        lines.extend([
            "# 1. Build Paleo-Globe using GlobeModel.from_paleo()",
            "model = GlobeModel.from_paleo(",
            f"    age={pc.age},",
            f"    radius={geom.radius},",
            f"    n_points={geom.n_points},",
            f"    hollow={geom.hollow},",
            f"    inner_ratio={geom.inner_ratio},",
            f"    vert_exagg={pc.vert_exagg},",
            f"    coastline_step={pc.coastline_step},",
            f"    mark_poles={pc.mark_poles},",
            f"    tracked_locations={tracked_repr},",
            f"    method={geom.distribution!r},",
            ")",
            "",
        ])
    else:
        lines.extend([
            "# 1. Initialize Spherical Mesh",
            "model = GlobeModel(",
            f"    method={geom.distribution!r},",
            f"    n_points={geom.n_points},",
            f"    radius={geom.radius},",
            f"    center={tuple(geom.center[:3])!r},",
            f"    hollow={geom.hollow and geom.create_inner_mesh_from_outer_thickness is None},",
            f"    inner_ratio={geom.inner_ratio},",
            f"    inner_n_points={geom.inner_n_points!r},",
            ")",
            "",
            "# 2. Load & Preprocess Geographic Grids",
            "grids = {}",
        ])

        for g in project.grids:
            gid = g.id
            if g.source == "online":
                ds_call = g.dataset or "topography.earth"
                params_kw = ", ".join(f"{k}={v!r}" for k, v in (g.params or {}).items())
                lines.append(f"grids[{gid!r}] = datasets.{ds_call}({params_kw})")
            elif g.source == "paleo":
                age_val = (g.params or {}).get("age", 250.0)
                res_val = (g.params or {}).get("resolution", "1d")
                lines.append(f"grids[{gid!r}], _, _ = datasets.paleo.scotese(age={age_val}, resolution={res_val!r})")
            elif g.source == "local":
                lines.append(f"grids[{gid!r}] = datasets._load_netcdf_grid({g.filepath!r})")
            else:
                lines.append(f"# Synthetic grid '{gid}'")
                lines.append("lats = np.linspace(-90.0, 90.0, 181)")
                lines.append("lons = np.linspace(-180.0, 180.0, 361)")
                lines.append("lon_m, lat_m = np.meshgrid(lons, lats)")
                lines.append(
                    f"grids[{gid!r}] = GeographicGrid(lats, lons, 3000.0 * np.sin(np.radians(3 * lat_m)) * np.cos(np.radians(4 * lon_m)))"
                )

            for op in g.ops:
                if op.op == "downsample" and op.factor > 1:
                    f = op.factor
                    lines.append(
                        f"grids[{gid!r}] = GeographicGrid(grids[{gid!r}].lats[::{f}], grids[{gid!r}].lons[::{f}], grids[{gid!r}].grid[::{f}, ::{f}])"
                    )
                elif op.op == "scale_offset":
                    lines.append(
                        f"grids[{gid!r}] = GeographicGrid(grids[{gid!r}].lats, grids[{gid!r}].lons, grids[{gid!r}].grid * {op.scale} + {op.offset})"
                    )
        lines.append("")

        lines.append("# 3. Apply Outer & Inner Displacements")
        for d in project.outer_displacements:
            if not d.enabled:
                continue
            if d.type == "GridDisplacer":
                gid = d.grid_id or (project.grids[0].id if project.grids else "default")
                if d.scale_mode == "explicit":
                    lines.append(f"scale = {d.scale}")
                else:
                    lines.append(
                        f"scale = calculate_displacement_scale({geom.radius}, grid_units={d.data_unit!r}) * {d.vert_exagg}"
                    )
                coast_expr = (
                    f"{d.coastline_step} / scale"
                    if (0.0 < abs(d.coastline_step) <= 20.0)
                    else f"{d.coastline_step}"
                )
                lines.append(
                    f"model.outer.displace(GridDisplacer(grids[{gid!r}], reference_level={d.reference_level}, coastline_step={coast_expr}, step_threshold={d.step_threshold}), scale=scale)"
                )
            elif d.type == "ConstantDisplacer":
                lines.append(f"model.outer.displace(ConstantDisplacer({d.value}), scale={d.scale})")
            elif d.type == "PolygonDisplacer":
                shp_expr = repr(d.shapefile) if d.shapefile else "datasets.shapefiles.land()"
                disp_val = float(d.displacement if d.displacement is not None else d.height)
                inside_val = bool(d.displace_inside if hasattr(d, "displace_inside") and d.displace_inside is not None else True)
                lines.append(
                    f"model.outer.displace(PolygonDisplacer({shp_expr}, displacement={disp_val}, displace_inside={inside_val}), scale=1.0)"
                )
            elif d.type == "LineDisplacer":
                shp_expr = repr(d.shapefile) if d.shapefile else "datasets.shapefiles.coastline()"
                disp_val = float(d.displacement if d.displacement is not None else d.height)
                lines.append(
                    f"model.outer.displace(LineDisplacer({shp_expr}, displacement={disp_val}, width_degrees={d.width_deg}), scale=1.0)"
                )
            elif d.type == "PointDisplacer":
                disp_val = float(d.displacement if d.displacement is not None else d.height)
                pts_expr = repr(d.shapefile or d.points)
                lines.append(
                    f"model.outer.displace(PointDisplacer({pts_expr}, displacement={disp_val}, radius_degrees={d.radius_deg}), scale=1.0)"
                )

        if geom.hollow and geom.create_inner_mesh_from_outer_thickness is not None:
            lines.append(f"model.create_inner_mesh(thickness={geom.create_inner_mesh_from_outer_thickness})")

        for d in project.inner_displacements:
            if not d.enabled:
                continue
            if d.type == "GridDisplacer":
                gid = d.grid_id or (project.grids[0].id if project.grids else "default")
                lines.append(
                    f"inner_scale = calculate_displacement_scale({geom.radius * geom.inner_ratio}, grid_units={d.data_unit!r}) * {d.vert_exagg}"
                )
                lines.append(
                    f"model.inner.displace(GridDisplacer(grids[{gid!r}], reference_level={d.reference_level}), scale=inner_scale)"
                )
        lines.append("")

        lines.append("# 4. Apply Vertex Colouring Layers")
        for c in project.colourers:
            if not c.enabled:
                continue
            sel_arg = "None" if c.selection == "all" else repr(c.selection)
            if c.type == "GridColourer":
                gid = c.grid_id or (project.grids[0].id if project.grids else "default")
                lines.append(
                    f"model.colour(GridColourer(grids[{gid!r}], colormap={c.cmap!r}, vmin={c.vmin!r}, vmax={c.vmax!r}), target={c.target!r}, selection={sel_arg})"
                )
            elif c.type == "ConstantColourer":
                lines.append(
                    f"model.colour(ConstantColourer({c.color!r}), target={c.target!r}, selection={sel_arg})"
                )
            elif c.type == "PolygonColourer":
                shp_expr = repr(c.shapefile) if c.shapefile else "datasets.shapefiles.land()"
                inside_val = bool(c.flood_inside if hasattr(c, "flood_inside") else True)
                lines.append(
                    f"model.colour(PolygonColourer({shp_expr}, color={c.color!r}, flood_inside={inside_val}), target={c.target!r}, selection={sel_arg})"
                )
            elif c.type == "LineColourer":
                shp_expr = repr(c.shapefile) if c.shapefile else "datasets.shapefiles.coastline()"
                lines.append(
                    f"model.colour(LineColourer({shp_expr}, color={c.color!r}, width_degrees={c.width_deg}), target={c.target!r}, selection={sel_arg})"
                )
            elif c.type == "ImageColourer":
                img_expr = repr(c.image_path) if c.image_path else "None"
                lines.append(
                    f"model.colour(ImageColourer({img_expr}), target={c.target!r}, selection={sel_arg})"
                )
            elif c.type == "SymbolColourer":
                lines.append(
                    f"model.colour(SymbolColourer(symbol={c.symbol!r}, lat={c.lat}, lon={c.lon}, radius_degrees={c.size_deg}, color={c.color!r}), target={c.target!r})"
                )
            elif c.type == "PoleLabelColourer":
                lines.append(
                    f"model.colour(PoleLabelColourer(radius_degrees={c.size_deg}), target={c.target!r})"
                )
            elif c.type == "TextColourer":
                lines.append(
                    f"model.colour(TextColourer(text={c.text!r}, lat={c.lat}, lon={c.lon}, height_degrees={c.size_deg}, color={c.color!r}), target={c.target!r})"
                )
        lines.append("")

    if geom.hollow and geom.fix_intersection.enabled:
        lines.extend([
            "# Enforce minimum shell wall thickness",
            f"model.fix_intersection(min_thickness={geom.fix_intersection.min_thickness}, mode={geom.fix_intersection.mode!r})",
            "",
        ])

    if mag.enabled:
        pos_val = "'auto'" if mag.Optimize_positions else repr(mag.manual_angles or mag.count)
        lines.extend([
            "# Configure Equatorial Magnets",
            "model.configure_magnets(",
            f"    diameter={mag.diameter},",
            f"    height={mag.height},",
            f"    n_magnets={mag.count},",
            f"    position={pos_val},",
            f"    horizontal_tolerance={mag.clearance},",
            f"    vertical_tolerance={mag.clearance},",
            f"    min_thickness={mag.min_margin},",
            f"    allow_bosses={mag.boss_thickness > 0},",
            ")",
            "",
        ])

    ext = f".{exp.format.lower().lstrip('.')}"
    lines.append(f"os.makedirs({exp.output_dir!r}, exist_ok=True)")
    if exp.split_hemispheres:
        if ext == ".3mf" and not exp.dual_files:
            out_file = f"{exp.output_dir}/{exp.filename_prefix}_hemispheres{ext}"
            lines.append(f"model.export_hemispheres({out_file!r}, hollow={geom.hollow})")
        else:
            top_f = f"{exp.output_dir}/{exp.filename_prefix}_north{ext}"
            bot_f = f"{exp.output_dir}/{exp.filename_prefix}_south{ext}"
            lines.append(f"model.export_hemispheres({top_f!r}, {bot_f!r}, hollow={geom.hollow})")
    else:
        out_file = f"{exp.output_dir}/{exp.filename_prefix}{ext}"
        lines.append(f"model.export({out_file!r})")

    python_script = "\n".join(lines) + "\n"

    notebook_obj = {
        "cells": [
            {
                "cell_type": "markdown",
                "metadata": {},
                "source": [
                    f"# {meta.name}\n",
                    f"{meta.description}\n\n",
                    "*Generated by Globe3D Studio WebApp*\n",
                ],
            },
            {
                "cell_type": "code",
                "execution_count": None,
                "metadata": {},
                "outputs": [],
                "source": [line + "\n" for line in lines],
            },
        ],
        "metadata": {
            "kernelspec": {
                "display_name": "Python 3 (pygmt)",
                "language": "python",
                "name": "python3",
            },
            "language_info": {
                "name": "python",
                "version": "3.11",
            },
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }

    return {
        "python_script": python_script,
        "notebook_json": json.dumps(notebook_obj, indent=2),
    }
